import { expect, test } from '@playwright/test'

test('Manager creates, edits and persists coupons on desktop and mobile', async ({ page }) => {
  await page.route('**/api/v1/auth/me', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ data: { id: 1, name: 'Manager', role: 'manager' } }) }))
  await page.goto('/kupon')
  await page.getByRole('button', { name: 'Buat Kupon', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nama promo').fill('Promo Studio')
  await dialog.getByLabel('Kode kupon').fill('STUDIO10')
  await dialog.getByLabel('Tanggal mulai').fill('2026-01-01')
  await dialog.getByLabel('Tanggal berakhir').fill('2099-12-31')
  await dialog.getByRole('button', { name: 'Simpan Kupon' }).click()
  await expect(page.getByRole('table')).toContainText('STUDIO10')
  await page.reload()
  await expect(page.getByRole('table')).toContainText('STUDIO10')
  await page.getByRole('button', { name: 'Edit STUDIO10', exact: true }).click()
  await dialog.getByLabel('Jenis diskon').selectOption('fixed')
  await dialog.getByLabel('Nilai diskon').fill('50000')
  await dialog.getByRole('button', { name: 'Simpan Kupon' }).click()
  await expect(page.getByRole('table')).toContainText('50.000')
  await page.getByRole('button', { name: 'Nonaktifkan STUDIO10', exact: true }).click()
  await expect(page.getByRole('table').getByText('Nonaktif', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Cari kupon' }).fill('tidak-ada')
  await expect(page.getByText('Kupon tidak ditemukan')).toBeVisible()
  await page.getByRole('textbox', { name: 'Cari kupon' }).fill('')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: 'test-results/coupons-mobile.png', fullPage: true })
})
